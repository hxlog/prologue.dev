/** Circular avatar with the brand gradient ring, falling back to an initial. */
function AvatarImage({ dataUri }) {
  if (dataUri) {
    return (
      <div
        style={{
          display: "flex",
          width: 64,
          height: 64,
          borderRadius: 999,
          padding: 3,
          background: brandGradient,
        }}
      >
        {/* next/og accepts an <img> with a data URI; Satori needs explicit
            width/height and borderRadius to clip. next/image cannot be used
            here: Satori serialises this tree to its own layout, not React DOM. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={dataUri}
          alt=""
          width={58}
          height={58}
          style={{ borderRadius: 999, objectFit: "cover" }}
        />
      </div>
    );
  }

  return (
    <div
      style={{
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        width: 64,
        height: 64,
        borderRadius: 999,
        padding: 3,
        background: brandGradient,
        fontSize: 28,
        fontWeight: 700,
        color: palette.accent,
      }}
    >
      <div
        style={{
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          width: "100%",
          height: "100%",
          borderRadius: 999,
          backgroundColor: palette.surface,
        }}
      >
        {siteMetadata.author.slice(0, 1)}
      </div>
    </div>
  );
}

function CardElement({ card, avatar }) {
  const { title, date, read, tags, isPost } = card;
  return (
    <div
      style={{
        width: OG_CARD_WIDTH,
        height: OG_CARD_HEIGHT,
        display: "flex",
        position: "relative",
        backgroundColor: palette.paper,
        color: palette.ink,
        fontFamily: "Noto Sans SC",
        overflow: "hidden",
      }}
    >
      {/* Three soft blooms, same three hues as the rim. Satori has no blur, so
          each is a wide radial gradient fading to transparent before the box
          edge. */}
      <div
        style={{
          position: "absolute",
          top: 0,
          left: 0,
          right: 0,
          bottom: 0,
          display: "flex",
          background:
            "radial-gradient(760px 560px at 14% 8%, rgba(201,205,245,0.72), transparent 72%)," +
            "radial-gradient(720px 520px at 86% 6%, rgba(180,224,236,0.62), transparent 74%)," +
            "radial-gradient(820px 520px at 64% 104%, rgba(247,212,230,0.66), transparent 74%)",
        }}
      />

      {/* 2px tri-hue rim: an outer box painted with the gradient and 2px of
          padding, with the white card sitting inside it. Satori cannot mask a
          conic border, and a real border cannot hold a gradient. */}
      <div
        style={{
          position: "absolute",
          top: 40,
          left: 40,
          right: 40,
          bottom: 40,
          display: "flex",
          flexDirection: "column",
          padding: 2,
          borderRadius: 28,
          background: rimGradient,
        }}
      >
        <div
          style={{
            position: "relative",
            display: "flex",
            flexDirection: "column",
            flexGrow: 1,
            padding: "40px 54px 36px",
            borderRadius: 26,
            backgroundColor: palette.surface,
            overflow: "hidden",
            boxShadow: "0 26px 60px -34px rgba(47,52,70,0.42)",
          }}
        >
          {/* Two star dots, a 5px one over a 4px one. The white ring is a 1px
              border; Satori has no spread box-shadow. */}
          <div
            style={{
              position: "absolute",
              top: 26,
              right: 28,
              display: "flex",
              width: 5,
              height: 5,
              borderRadius: 999,
              backgroundColor: "rgba(170,160,252,0.95)",
              border: "1px solid rgba(255,255,255,0.85)",
            }}
          />
          <div
            style={{
              position: "absolute",
              top: 38,
              right: 44,
              display: "flex",
              width: 4,
              height: 4,
              borderRadius: 999,
              backgroundColor: "rgba(252,156,200,0.95)",
              border: "1px solid rgba(255,255,255,0.85)",
            }}
          />

          {/* Meta row (posts only). The separator is a dot, not a glyph, so it
              never depends on the font subset. */}
          {isPost ? (
            <div
              style={{
                display: "flex",
                alignItems: "center",
                gap: 12,
                fontSize: 22,
                lineHeight: 1.4,
                color: palette.muted,
              }}
            >
              {date ? <span>{formatDate(date)}</span> : null}
              {date && read ? (
                <div
                  style={{
                    display: "flex",
                    width: 5,
                    height: 5,
                    borderRadius: 999,
                    backgroundColor: "rgba(47,52,70,0.22)",
                  }}
                />
              ) : null}
              {read ? <span>{read}</span> : null}
            </div>
          ) : null}

          {/* Title. flexGrow pushes the footer down and lets the page card
              centre a short title in the whole card. */}
          <div
            style={{
              display: "flex",
              flexGrow: 1,
              minHeight: 0,
              marginTop: isPost ? 22 : 0,
              alignItems: isPost ? "flex-start" : "center",
              justifyContent: isPost ? "flex-start" : "center",
              fontSize: isPost ? titleSize(title) : 68,
              fontWeight: 600,
              lineHeight: isPost ? 1.2 : 1.24,
              letterSpacing: -0.8,
              color: palette.ink,
            }}
          >
            <div
              style={{
                display: "-webkit-box",
                WebkitBoxOrient: "vertical",
                WebkitLineClamp: 3,
                overflow: "hidden",
                textAlign: isPost ? "left" : "center",
              }}
            >
              {title}
            </div>
          </div>

          <div
            style={{
              display: "flex",
              height: 1,
              marginBottom: 22,
              background: hairlineGradient,
            }}
          />

          {/* Author strip + stardust chips. The gradient hairline above is the
              only rule on the card; there is no border under the footer. */}
          <div
            style={{
              display: "flex",
              alignItems: "center",
              justifyContent: isPost ? "space-between" : "center",
              gap: 20,
            }}
          >
            <div style={{ display: "flex", alignItems: "center", gap: 16 }}>
              <AvatarImage dataUri={avatar} />
              <div style={{ display: "flex", flexDirection: "column" }}>
                <div
                  style={{
                    display: "flex",
                    fontSize: 26,
                    fontWeight: 600,
                    color: palette.ink,
                    lineHeight: 1.25,
                  }}
                >
                  {siteMetadata.author}
                </div>
                <div
                  style={{
                    display: "flex",
                    fontSize: 20,
                    marginTop: 3,
                    color: palette.faint,
                    lineHeight: 1.3,
                  }}
                >
                  {domain()}
                </div>
              </div>
            </div>

            {isPost && tags.length > 0 ? (
              <div style={{ display: "flex", alignItems: "center", gap: 10 }}>
                {tags.slice(0, 3).map((tag) => (
                  <div
                    key={tag}
                    style={{
                      display: "flex",
                      alignItems: "center",
                      height: 40,
                      padding: "0 18px",
                      borderRadius: 999,
                      fontSize: 20,
                      fontWeight: 500,
                      color: palette.muted,
                      background:
                        "linear-gradient(140deg, rgba(170,160,252,0.066), rgba(84,208,238,0.048) 55%, rgba(252,156,200,0.066))",
                      border: "1px solid rgba(170,160,252,0.14)",
                    }}
                  >
                    {tagLabel(tag)}
                  </div>
                ))}
                {tags.length > 3 ? (
                  <div
                    style={{
                      display: "flex",
                      alignItems: "center",
                      justifyContent: "center",
                      height: 40,
                      padding: "0 15px",
                      borderRadius: 999,
                      fontSize: 20,
                      fontWeight: 600,
                      color: palette.faint,
                      border: "1px dashed rgba(47,52,70,0.26)",
                    }}
                  >
                    +{tags.length - 3}
                  </div>
                ) : null}
              </div>
            ) : null}
          </div>
        </div>
      </div>
    </div>
  );
}

/**
 * Render one card.
 *
 * @param {{title?: string, date?: string, read?: string, tags?: string[], kind?: "post"|"page"}} input
 * @param {new (element: any, options?: any) => Response} ImageResponse
 *   The `next/og` ImageResponse constructor. Passed in because plain Node
 *   cannot import `next/og` as ESM; the build script imports `next/og.js`.
 * @returns {Promise<{response: Response, png: Buffer, meta: {title: string, kind: string, fontSource: "local"|"remote", width: number, height: number}}>}
 */
export async function renderOgCard(input, ImageResponse) {
  if (typeof ImageResponse !== "function") {
    throw new TypeError("[og] renderOgCard requires the ImageResponse constructor");
  }

  const card = normalizeInput(input);
  const text = cardText(card);
  const { fonts, source } = await resolveFonts(text);
  const avatar = avatarDataUri();

  const response = new ImageResponse(<CardElement card={card} avatar={avatar} />, {
    width: OG_CARD_WIDTH,
    height: OG_CARD_HEIGHT,
    ...(fonts.length ? { fonts } : {}),
  });

  const png = Buffer.from(await response.arrayBuffer());
  return {
    response,
    png,
    meta: {
      title: card.title,
      kind: card.kind,
      fontSource: source,
      width: OG_CARD_WIDTH,
      height: OG_CARD_HEIGHT,
    },
  };
}

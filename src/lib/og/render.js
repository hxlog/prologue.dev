/**
 * OG card renderer (Satori via next/og), extracted from the old request-time
 * /og route so it can run in a plain Node build script.
 *
 * The card is 1200×630, light mode, v4 "stardust edge": three pastel blooms on
 * the paper field, a white card inset 40px inside a 2px tri-hue rim
 * (lavender → sky → pink), two star dots top-right, a gradient hairline above
 * the footer, and 40px "stardust" tag chips. Post cards carry date / reading
 * time / up to 3 tag labels + a +N chip; page cards centre the title and drop
 * those rows.
 *
 * Everything is drawn with Satori-safe primitives only: flexbox, absolute
 * positioning, linear-/radial-gradients, boxShadow, border and borderRadius.
 * Satori has no filter: blur and no CSS grid, so the soft blooms are stacked
 * radial gradients and the rim is a padded gradient box rather than a masked
 * conic border.
 *
 * Fonts: the Noto Sans SC subsets in assets/og/, generated by
 * scripts/build-og-font.mjs, are read once per process. If a drawn character is
 * not in the subset, the legacy per-card Google Fonts text= subset is fetched
 * as a fallback so a card never falls back to tofu. The avatar is inlined from
 * assets/og/avatar-152.png (pre-resized, no sharp at render time).
 *
 * Node-only by design: it reads assets from disk and takes the ImageResponse
 * constructor as an argument (plain Node cannot import `next/og` as ESM; the
 * build script imports `next/og.js` and injects it). App code should not import
 * this module — the request-time route is retired.
 */

import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import siteMetadata from "../../../data/sitemetadata.js";
import { tagLabel } from "../../../data/tagLabels.js";
import { formatDate } from "../date.js";
import {
  OG_IMAGE_HEIGHT,
  OG_IMAGE_WIDTH,
} from "./keys.js";

export const OG_CARD_WIDTH = OG_IMAGE_WIDTH;
export const OG_CARD_HEIGHT = OG_IMAGE_HEIGHT;

const ASSET_DIR = fileURLToPath(new URL("../../../assets/og/", import.meta.url));

// The three weights the card draws with: 400 meta row, 600 title/author/+N,
// 700 the initial-letter avatar. Keep in sync with scripts/build-og-font.mjs.
const WEIGHTS = [400, 600, 700];

const palette = {
  paper: "#f7f8fc",
  surface: "#ffffff",
  ink: "#2f3446",
  muted: "#5d6579",
  faint: "#767e92",
  lavender: "#c9cdf5",
  pink: "#f7d4e6",
  sky: "#b4e0ec",
  accent: "#6a6fcd",
  secondary: "#b85680",
  border: "rgba(47, 52, 70, 0.10)",
};

// v3 brand gradient: the same three stops as --gradient-brand (lavender ->
// sky -> pink), so the rim, the avatar ring and the hairline cannot drift.
const brandGradient = `linear-gradient(120deg, ${palette.lavender}, ${palette.sky} 46%, ${palette.pink})`;
const rimGradient =
  "linear-gradient(135deg, rgba(201,205,245,0.95), rgba(180,224,236,0.85) 46%, rgba(247,212,230,0.95))";
const hairlineGradient =
  "linear-gradient(90deg, rgba(170,160,252,0.28), rgba(84,208,238,0.22) 56%, rgba(252,156,200,0.28))";

/** Normalise the loose card input the script/route may hand over. */
function normalizeInput(input = {}) {
  const tags = Array.isArray(input.tags)
    ? input.tags.map((tag) => clip(tag, 24)).filter(Boolean).slice(0, 4)
    : [];
  const date = clip(input.date, 40);
  const read = clip(input.read, 20);
  const kind =
    input.kind === "post" || input.kind === "page"
      ? input.kind
      : date || tags.length
        ? "post"
        : "page";
  return {
    title: clip(input.title, 90) || siteMetadata.publishName,
    date,
    read,
    tags,
    kind,
    isPost: kind === "post",
  };
}

/** The exact string the card draws; also used for the font-subset coverage test. */
export function cardText(input) {
  const card = normalizeInput(input);
  return [
    card.title,
    card.date ? formatDate(card.date) : "",
    card.read,
    blogName(),
    domain(),
    siteMetadata.author,
    ...card.tags.map(tagLabel),
    "+0123456789",
  ].join("");
}

function clip(value, max) {
  return String(value || "").trim().slice(0, max);
}

function domain() {
  return String(siteMetadata.siteUrl || "")
    .replace(/^https?:\/\//, "")
    .replace(/\/+$/, "");
}

function blogName() {
  return siteMetadata.publishName;
}

/** Title size: 62px base, stepping down so a long headline still fits 3 lines. */
function titleSize(title) {
  if (title.length > 56) return 46;
  if (title.length > 40) return 54;
  return 62;
}

/** Small non-cryptographic hash, only used as a font-cache key. */
function hash(text) {
  let h = 5381;
  for (let i = 0; i < text.length; i++) {
    h = ((h << 5) + h + text.charCodeAt(i)) | 0;
  }
  return h.toString(36);
}

// ---------------------------------------------------------------------------
// Assets: fonts + avatar, memoised per process
// ---------------------------------------------------------------------------

/**
 * The build-time subset from scripts/build-og-font.mjs: three TTFs plus the
 * glyphs.json coverage table. Returns null when the assets are unavailable so
 * callers fall back to the per-card Google subset.
 */
let localFontsCache;
function localFontSet() {
  if (localFontsCache !== undefined) return localFontsCache;
  try {
    const coverage = JSON.parse(
      readFileSync(path.join(ASSET_DIR, "glyphs.json"), "utf8")
    );
    const fonts = WEIGHTS.map((weight) => ({
      name: "Noto Sans SC",
      data: readFileSync(path.join(ASSET_DIR, `NotoSansSC-${weight}.ttf`)),
      weight,
      style: "normal",
    }));
    localFontsCache = { fonts, codepoints: new Set(coverage.codepoints) };
  } catch {
    localFontsCache = null;
  }
  return localFontsCache;
}

/** The codepoints the committed subset covers, or null if it is unavailable. */
export function localGlyphSet() {
  return localFontSet()?.codepoints ?? null;
}

/** Whether the committed subset can draw every character of `text`. */
export function hasLocalGlyphCoverage(text) {
  const set = localFontSet();
  if (!set) return false;
  for (const char of String(text ?? "")) {
    if (!set.codepoints.has(char.codePointAt(0))) return false;
  }
  return true;
}

let avatarData;
/** The avatar, inlined as a data URI; degrades to an initial-letter avatar. */
function avatarDataUri() {
  if (avatarData !== undefined) return avatarData;
  try {
    const png = readFileSync(path.join(ASSET_DIR, "avatar-152.png"));
    avatarData = `data:image/png;base64,${png.toString("base64")}`;
  } catch {
    avatarData = null;
  }
  return avatarData;
}

const fontCache = new Map();

/**
 * Fetch the Noto Sans SC text= subsets for the characters drawn — the fallback
 * path used only when the committed subset does not cover them.
 *
 * One request per weight. Google's CSS2 endpoint picks the format from the
 * User-Agent; the legacy UA is what makes it serve a TTF (Satori cannot parse
 * woff2). A failed weight is dropped rather than retried: Satori still needs at
 * least one font covering the text, and 700 covers the same characters.
 */
async function loadFonts(text) {
  const results = await Promise.all(WEIGHTS.map((weight) => loadFont(weight, text)));
  const fonts = [];
  results.forEach((data, i) => {
    if (!data) return;
    fonts.push({ name: "Noto Sans SC", data, weight: WEIGHTS[i], style: "normal" });
  });
  return fonts;
}

async function loadFont(weight, text) {
  const key = `${weight}:${hash(text)}`;
  if (fontCache.has(key)) return fontCache.get(key);

  try {
    const css = await (
      await fetch(
        `https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@${weight}&text=${encodeURIComponent(text)}`,
        {
          headers: {
            "User-Agent":
              "Mozilla/5.0 (BB10; Touch) AppleWebKit/537.1+ (KHTML, like Gecko) Version/10.0.0.1337 Mobile Safari/537.1+",
          },
        }
      )
    ).text();

    const match = css.match(/src: url\((.+?)\) format\('(opentype|truetype)'\)/);
    if (!match) return null;

    const res = await fetch(match[1]);
    if (!res.ok) return null;
    const data = await res.arrayBuffer();

    if (fontCache.size > 240) fontCache.clear();
    fontCache.set(key, data);
    return data;
  } catch {
    return null;
  }
}

/**
 * Resolve the fonts for a drawn text. Local subset first (no network); the
 * per-card Google subset only when the committed assets cannot draw a character.
 */
async function resolveFonts(text) {
  if (hasLocalGlyphCoverage(text)) {
    return { fonts: localFontSet().fonts, source: "local" };
  }
  const remote = await loadFonts(text);
  if (remote.length === 0) {
    throw new Error(
      "[og] no font available: the committed subset is missing characters of " +
        JSON.stringify(text.slice(0, 60)) +
        " and the Google Fonts fallback failed (offline?). " +
        "Run `node scripts/build-og-font.mjs` to refresh assets/og when online."
    );
  }
  return { fonts: remote, source: "remote" };
}

